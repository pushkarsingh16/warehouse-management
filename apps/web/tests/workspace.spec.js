test('stock receipts update over sockets, reconnect refetches, cancellation releases reservations', async ({ page, context }) => {
  await login(page); await nav(page, 'Inventory');
  await page.getByLabel('Search inventory').fill('DEMO-010');
  let row = page.locator('tbody tr').filter({ hasText: 'DEMO-010' });
  const original = Number((await row.locator('td').nth(2).textContent()).replaceAll(',', ''));
  await row.getByRole('button', { name: 'Update stock' }).click();
  await page.getByLabel('Quantity', { exact: true }).fill('1');
  await page.getByLabel('Reason', { exact: true }).fill('Browser verification receipt');
  await page.getByRole('button', { name: 'Save stock update' }).click();
  await expect(row.locator('td').nth(2)).toHaveText(String(original + 1));
  await context.setOffline(true);
  await expect(page.getByText('Reconnecting to live updates')).toBeVisible();
  await context.setOffline(false);
  await expect(page.getByText('Live connection active')).toBeVisible();
  const me = (await (await page.request.get('/api/v1/auth/me')).json()).data;
  const inv = (await (await page.request.get(`/api/v1/inventory?warehouseId=${me.warehouseIds[0]}&limit=100`)).json()).data;
  const products = (await (await page.request.get('/api/v1/products?limit=100')).json()).data;
  const p = products.find(p => p.sku === 'DEMO-010'), balance = inv.find(b => b.productId === p._id);
  const receipt = await page.request.post('/api/v1/inventory/receipts', { headers: { Origin: new URL(page.url()).origin, 'X-CSRF-Token': me.csrf, 'Idempotency-Key': crypto.randomUUID() }, data: { warehouseId: balance.warehouseId, productId: balance.productId, binId: balance.binId, quantity: 1, reason: 'External live update verification' } });
  expect(receipt.ok()).toBeTruthy();
  await expect(row.locator('td').nth(2)).toHaveText(String(original + 2), { timeout: 10000 });
  await nav(page, 'Orders');
  await page.getByRole('button', { name: 'Create order', exact: true }).click();
  await page.getByLabel('Product 1', { exact: true }).selectOption(p._id);
  await page.getByLabel('Quantity 1', { exact: true }).fill('2');
  const created = page.waitForResponse(r => r.url().endsWith('/api/v1/orders') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Reserve inventory & create' }).click();
  const order = (await (await created).json()).data;
  const orderRow = page.locator('tbody tr').filter({ hasText: `#${order._id.slice(-7).toUpperCase()}` });
  await orderRow.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(orderRow).toContainText('cancelled');
  const after = (await (await page.request.get(`/api/v1/inventory?warehouseId=${balance.warehouseId}&productId=${p._id}`)).json()).data[0];
  expect(after.reserved).toBe(balance.reserved); expect(after.onHand).toBe(original + 2);
});
test('WebGL failure keeps bins usable on a small reduced-motion screen', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.addInitScript(() => { const original = HTMLCanvasElement.prototype.getContext; HTMLCanvasElement.prototype.getContext = function(type, ...args) { if (type === 'webgl' || type === 'webgl2' || type === 'experimental-webgl') return null; return original.call(this, type, ...args); }; });
  await login(page, 'viewer');
  await expect(page.getByText('3D is unavailable on this device. All bins remain accessible below.')).toBeVisible();
  await page.locator('.bin-map button').first().click();
  await expect(page.locator('.selected-product')).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
});
